import argparse
import math
import sys

import numpy as np
from qiskit import QuantumCircuit
from qiskit.quantum_info import SparsePauliOp, Statevector
from scipy.optimize import minimize

from applog import get_logger

log = get_logger("lab08")

# Qiskit is little-endian: bit k of a probability index is qubit k. Everything
# below uses that convention, so sampled parities need no re-ordering.
CHEM_ACC = 1.6e-3  # 1.6 mHa: the accuracy chemistry asks for
# (coefficient, {qubit: pauli}) terms of the 2-qubit H2-style Hamiltonian.
TERMS = [
    (-0.4804, {}),
    (0.3435, {0: "Z"}),
    (-0.4347, {1: "Z"}),
    (0.5716, {0: "Z", 1: "Z"}),
    (0.0910, {0: "Y", 1: "Y"}),
    (0.0910, {0: "X", 1: "X"}),
]
# QAOA graph: a 4-cycle plus one diagonal. Max cut = 4 (even/odd vertices).
EDGES = [(0, 1), (1, 2), (2, 3), (3, 0), (0, 2)]


def hamiltonian():
    """Build H as a SparsePauliOp from the (coef, paulis) term list."""
    # from_sparse_list wants (pauli string, qubit indices, coefficient); the
    # identity term has no qubits, so give it a harmless "I" on qubit 0.
    sparse = [("".join(p.values()) or "I", list(p) or [0], c) for c, p in TERMS]
    return SparsePauliOp.from_sparse_list(sparse, num_qubits=2)


def ansatz(theta):
    """Hardware-efficient ansatz: Ry layer, entangler, Ry layer (4 angles).

    Ry keeps all amplitudes real, which is enough here because H is real
    (its ground state can be chosen real). Fewer parameters mean an easier
    optimisation problem and a shallower, less noisy circuit.
    """
    qc = QuantumCircuit(2)
    qc.ry(theta[0], 0)
    qc.ry(theta[1], 1)
    qc.cx(0, 1)
    qc.ry(theta[2], 0)
    qc.ry(theta[3], 1)
    return qc


def energy(theta, ham):
    """Exact <psi(theta)|H|psi(theta)> using the statevector."""
    sv = Statevector.from_instruction(ansatz(theta))
    return float(np.real(sv.expectation_value(ham)))


def shift_gradient(theta, ham):
    """Parameter-shift rule: dE/dtheta_k = [E(+pi/2) - E(-pi/2)] / 2.

    Exact (not an approximation) for gates generated by a Pauli, like Ry, and
    it needs only ordinary circuit runs, so it works on real hardware where
    finite differences would drown in shot noise.
    """
    grad = np.zeros(len(theta))
    # One pair of circuit evaluations per parameter: cost grows linearly.
    for k in range(len(theta)):
        up, down = np.array(theta, float), np.array(theta, float)
        up[k] += math.pi / 2
        down[k] -= math.pi / 2
        grad[k] = (energy(up, ham) - energy(down, ham)) / 2
    return grad


def gradient_descent(theta0, ham, lr=0.4, steps=200):
    """Plain gradient descent on the parameter-shift gradient."""
    # lr=0.4 is large enough to move fast yet small enough not to overshoot
    # for this smooth 4-parameter landscape; real problems need tuning.
    theta = np.array(theta0, float)
    history = [energy(theta, ham)]
    for _ in range(steps):
        theta = theta - lr * shift_gradient(theta, ham)
        history.append(energy(theta, ham))
    return theta, history


def sampled_energy(theta, shots, rng):
    """Estimate E from measurement samples, one basis setting per Pauli type.

    A device only returns bitstrings in the Z basis. To read X or Y terms we
    rotate first (H for X; Sdg then H for Y). Each term's value is the parity
    (+1 / -1) of the measured bits on its qubits, averaged over shots.
    Returns (estimate, standard error).
    """
    # Terms with the same basis share one circuit, so 3 settings cover all 6.
    total, var = 0.0, 0.0
    for basis in ("Z", "X", "Y"):
        group = [(c, p) for c, p in TERMS if p and set(p.values()) == {basis}]
        if not group:
            continue
        qc = ansatz(theta)
        for q in (0, 1):
            if basis == "Y":
                qc.sdg(q)
            if basis in ("X", "Y"):
                qc.h(q)
        probs = Statevector.from_instruction(qc).probabilities()
        draws = rng.choice(len(probs), size=shots, p=probs)
        for c, p in group:
            # Vectorised parity of the measured bits on this term's qubits.
            parity = sum((draws >> q) & 1 for q in p)
            vals = 1 - 2 * (parity % 2)
            # Independent estimates add in variance: Var = sum c^2 Var/shots.
            total += c * float(vals.mean())
            var += (c**2) * float(vals.var()) / shots
    # The identity term needs no measurement: it is a constant offset.
    total += sum(c for c, p in TERMS if not p)
    return total, math.sqrt(var)


# ----------------------------------------------------------------------------
# QAOA for MaxCut
# ----------------------------------------------------------------------------
def cut_value(x):
    """Number of edges cut by the bipartition encoded in the bits of x."""
    return sum(((x >> i) & 1) != ((x >> j) & 1) for i, j in EDGES)


def qaoa_circuit(gammas, betas, n=4):
    """p alternating layers: cost phase separator, then X mixer.

    Cost layer exp(-i*gamma*C) with C = sum (1 - Z_i Z_j)/2 is one RZZ per
    edge (RZZ(t) = exp(-i t ZZ/2), so t = -gamma). It gives each bitstring a
    phase proportional to its cut value. The mixer RX(2*beta) on every qubit
    then turns those phase differences into amplitude differences.
    """
    qc = QuantumCircuit(n)
    qc.h(range(n))  # uniform superposition of all cuts
    for gamma, beta in zip(gammas, betas):
        for i, j in EDGES:
            qc.rzz(-gamma, i, j)
        qc.rx(2 * beta, range(n))
    return qc


def expected_cut(params, p):
    """<C> for params = [gamma_1..gamma_p, beta_1..beta_p]."""
    probs = Statevector.from_instruction(
        qaoa_circuit(params[:p], params[p:])
    ).probabilities()
    return float(sum(pr * cut_value(x) for x, pr in enumerate(probs)))


def best_qaoa(p, rng, starts):
    """Multi-start Nelder-Mead; QAOA landscapes have many local optima."""
    best = None
    # Restart from several points and keep the best: a single local run can
    # stall in a poor optimum, a known QAOA/VQE hazard.
    for x0 in starts:
        res = minimize(
            lambda v: -expected_cut(v, p),
            x0,
            method="Nelder-Mead",
            options={"xatol": 1e-6, "fatol": 1e-9, "maxiter": 2000},
        )
        if best is None or res.fun < best.fun:
            best = res
    return -float(best.fun), best.x


def check(cond, label):
    """Log PASS/FAIL and return the boolean for tallying."""
    (log.ok if cond else log.fail)("%s", label)
    return bool(cond)


def check_vqe(shots, seed, r):
    """Checks 1-5: the VQE half of the lab."""
    ham = hamiltonian()
    # Exact diagonalisation is the reference; it is only possible because
    # the system is 2 qubits. VQE exists for sizes where this is impossible.
    exact = np.linalg.eigh(ham.to_matrix())
    e0, ground = float(exact[0][0]), exact[1][:, 0]
    rng = np.random.default_rng(seed)

    log.info("=== Check 1: Qiskit expectation equals NumPy linear algebra ===")
    log.info("exact ground energy of H = %.6f", e0)
    theta = rng.uniform(-math.pi, math.pi, 4)
    psi = Statevector.from_instruction(ansatz(theta)).data
    mine = float(np.real(psi.conj() @ ham.to_matrix() @ psi))
    r.append(
        check(
            abs(mine - energy(theta, ham)) < 1e-12,
            "<psi|H|psi> matches SparsePauliOp expectation",
        )
    )
    r.append(
        check(
            np.allclose(ham.to_matrix(), ham.to_matrix().conj().T),
            "H is Hermitian (real eigenvalues)",
        )
    )

    log.info("=== Check 2: variational principle, 500 random circuits ===")
    # Any state's energy is a weighted average of H's eigenvalues, so it can
    # never undercut the lowest one. Violations would mean a bug.
    energies = [energy(rng.uniform(-math.pi, math.pi, 4), ham) for _ in range(500)]
    log.info("lowest random energy %.4f, highest %.4f", min(energies), max(energies))
    r.append(check(min(energies) >= e0 - 1e-12, "E(theta) >= E0 always"))

    log.info("=== Check 3: parameter-shift gradient is exact ===")
    grad = shift_gradient(theta, ham)
    eps = 1e-6
    fd = np.array(
        [
            (
                energy(theta + eps * np.eye(4)[k], ham)
                - energy(theta - eps * np.eye(4)[k], ham)
            )
            / (2 * eps)
            for k in range(4)
        ]
    )
    r.append(
        check(
            np.allclose(grad, fd, atol=1e-6),
            f"max |shift - finite difference| = " f"{np.max(np.abs(grad - fd)):.1e}",
        )
    )

    log.info("=== Check 4: gradient descent finds the ground state ===")
    start = rng.uniform(-0.5, 0.5, 4)
    opt, hist = gradient_descent(start, ham)
    for it in (0, 10, 50, 200):
        log.info("iteration %3d: E = %.6f (error %.2e)", it, hist[it], hist[it] - e0)
    r.append(
        check(
            hist[-1] - e0 < CHEM_ACC,
            f"final error {hist[-1] - e0:.1e} Ha < 1.6e-3 (chemical)",
        )
    )
    psi_opt = Statevector.from_instruction(ansatz(opt)).data
    fid = float(abs(ground.conj() @ psi_opt) ** 2)
    r.append(check(fid > 0.999, f"overlap with exact ground state = {fid:.6f}"))

    log.info("=== Check 5: energy from sampled X / Y / Z measurements ===")
    est, err = sampled_energy(opt, shots, rng)
    log.info(
        "sampled E = %.5f +/- %.5f (exact at these angles %.5f)",
        est,
        err,
        energy(opt, ham),
    )
    r.append(
        check(
            abs(est - energy(opt, ham)) < 5 * err,
            "sampled estimate within 5 standard errors",
        )
    )


def check_qaoa(seed, r):
    """Checks 6-10: the QAOA half of the lab."""
    # Enumerate all 2^4 cuts once: cheap here, and the ground truth the
    # quantum result is judged against.
    rng = np.random.default_rng(seed)
    cuts = [cut_value(x) for x in range(16)]
    best_cut = max(cuts)

    log.info("=== Check 6: brute-force MaxCut on %d edges ===", len(EDGES))
    winners = [format(x, "04b")[::-1] for x in range(16) if cuts[x] == best_cut]
    log.info("max cut = %d, optimal bitstrings (q0 first) = %s", best_cut, winners)
    r.append(check(best_cut == 4, "maximum cut is 4"))
    random_avg = sum(cuts) / 16
    r.append(
        check(
            abs(random_avg - len(EDGES) / 2) < 1e-12,
            f"random guessing cuts {random_avg} edges on average",
        )
    )

    log.info("=== Check 7: p=1 QAOA beats random guessing ===")
    # Coarse grid first (the landscape is periodic, so this is exhaustive
    # enough to land in the right basin), then polish locally.
    grid = [
        (g, b)
        for g in np.linspace(0, 2 * math.pi, 25, endpoint=False)
        for b in np.linspace(0, math.pi, 13, endpoint=False)
    ]
    scored = sorted(grid, key=lambda gb: -expected_cut(list(gb), 1))
    e1, x1 = best_qaoa(1, rng, [np.array(gb) for gb in scored[:3]])
    log.info(
        "p=1: <C> = %.4f at gamma=%.3f beta=%.3f (ratio %.3f)",
        e1,
        x1[0],
        x1[1],
        e1 / best_cut,
    )
    r.append(
        check(
            random_avg < e1 < best_cut,
            f"random {random_avg} < p=1 optimum {e1:.4f} < {best_cut}",
        )
    )

    log.info("=== Check 8: p=2 is at least as good as p=1 ===")
    # Seeding p=2 with the p=1 optimum guarantees monotonic improvement
    # (setting the extra layer's angles to zero reproduces p=1 exactly).
    starts = [np.array([x1[0], 0.0, x1[1], 0.0])]
    starts += [rng.uniform(0, math.pi, 4) for _ in range(5)]
    e2, x2 = best_qaoa(2, rng, starts)
    log.info("p=2: <C> = %.4f (ratio %.3f)", e2, e2 / best_cut)
    r.append(check(e2 >= e1 - 1e-6, f"p=2 optimum {e2:.4f} >= p=1 {e1:.4f}"))

    log.info("=== Check 9: (gamma, beta) -> (-gamma, -beta) symmetry ===")
    # The start state and cost are real, so negating all angles complex
    # conjugates the final state and leaves every probability unchanged.
    r.append(
        check(
            abs(expected_cut(x2, 2) - expected_cut(-x2, 2)) < 1e-9,
            "expected cut is unchanged under sign flip",
        )
    )

    log.info("=== Check 10: the most likely outcome is a maximum cut ===")
    probs = Statevector.from_instruction(qaoa_circuit(x2[:2], x2[2:])).probabilities()
    top = int(np.argmax(probs))
    mass = float(sum(probs[x] for x in range(16) if cuts[x] == best_cut))
    log.info(
        "top bitstring %s (cut %d), P(optimal cut) = %.3f",
        format(top, "04b")[::-1],
        cuts[top],
        mass,
    )
    r.append(check(cuts[top] == best_cut, "argmax outcome cuts 4 edges"))
    r.append(
        check(
            mass > 0.5,
            f"optimal cuts get {mass:.3f} of the probability "
            f"(uniform would give {2 / 16:.3f})",
        )
    )


def main(argv=None):
    """Run every Lab 8 check; return the process exit code (0 = all passed)."""
    ap = argparse.ArgumentParser(description="Lab 8: VQE and QAOA")
    ap.add_argument(
        "--shots",
        type=int,
        default=100000,
        help="shots per measurement basis in the sampled VQE check",
    )
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args(argv)
    if args.shots < 1000:
        ap.error(f"--shots must be >= 1000. Got {args.shots}.")
    r = []
    check_vqe(args.shots, args.seed, r)
    check_qaoa(args.seed, r)

    bad = r.count(False)
    if bad:
        log.fail("%d of %d checks failed", bad, len(r))
        return 1
    log.ok("All %d checks passed", len(r))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        log.warn_("Interrupted by user")
        sys.exit(130)
